#!/usr/bin/env python3
"""Generate Metal kernels for an Anime4K v4 Restore CNN shader.

Usage: anime4k.py Anime4K_Restore_CNN_L.glsl Anime4K_Restore_CNN_L.metal

The network works on RGB at the input resolution. Each layer's two GLSL passes (4 outputs
each, same inputs) become one kernel computing all 8 outputs; inputs are read with
clamp-to-edge like libplacebo's texOff, and CReLU (max(+-x, 0)) is applied as they are
read. The last layer adds the input RGB and clamps to [0, 1], as libplacebo's output does.
"""

import sys

import numpy as np

import anime4k_weights as A
from winograd import F23, F43, combo

# Winograd layers (16 CReLU inputs -> 8 outputs): F(4, 3) across x F(2, 3) down, 8 tiles of
# 4x2 pixels per SIMD group, 4 SIMD groups: 32x8 pixels per threadgroup.
WIN_W, WIN_H = 32, 8
WIN_SW, WIN_SH = WIN_W + 2, WIN_H + 2

# Frame-to-frame reuse (see ArtCNNMetal reuseUnchangedBlocks): blocks skip when their 16x8
# cells are clean. A direct 3x3 layer depends on input 1 pixel away; a Winograd layer's
# rounding depends on its whole tile window, 4 pixels across and 2 down.
CELL_W, CELL_H = 16, 8
DIRTY_PARAMS = ["device const uchar *dirty [[buffer(0)]]", "constant uint &cells_x [[buffer(1)]]"]


def emit_dirty_check(emit, cells):
    """Return early when all of this threadgroup's `cells` mask cells are clean."""
    emit(f"    const uint cell = tgid.y * cells_x + tgid.x * {cells};")
    emit("    if (" + " && ".join(f"(tgid.x * {cells} + {i} >= cells_x || !dirty[cell + {i}])" for i in range(cells)) + ") {")
    emit("        return;  // nothing within the dependency radius changed since the last frame")
    emit("    }")

BLOCK_W, BLOCK_H = 16, 8
THREADS = BLOCK_W * BLOCK_H
STAGE_W, STAGE_H = BLOCK_W + 2, BLOCK_H + 2


def half(v):
    return f"{float(v):.9g}"


PRELUDE = """\
// Generated by Metal/anime4k.py from {source}. Do not edit by hand.
#include <metal_stdlib>
using namespace metal;

// Reads clamp at the image edges, like libplacebo's texOff.
constexpr sampler edge(coord::pixel, address::clamp_to_edge, filter::nearest);

static inline half4 load(texture2d<half> t, int2 p)
{{
    return t.sample(edge, float2(p) + 0.5f);
}}

static inline void store(texture2d<half, access::write> t, int2 p, half4 v)
{{
    if (p.x < int(t.get_width()) && p.y < int(t.get_height())) {{
        t.write(v, uint2(p));
    }}
}}

// OUTPUT scale=1 format=rgba16f
"""


def layer_kernel(index, layer, names):
    textures = []  # distinct input textures in the order of their first use
    for name, _ in layer.inputs:
        if name not in textures:
            textures.append(name)
    out_textures = layer.saves if not layer.residual else ["OUTPUT"]
    lines = []
    emit = lines.append
    emit(f"// {' + '.join(layer.passes)}")
    params = [f"texture2d<half> {names[t]} [[texture({i})]]" for i, t in enumerate(textures)]
    if layer.residual and "MAIN" not in textures:
        textures.append("MAIN")
        params.append(f"texture2d<half> MAIN [[texture({len(textures) - 1})]]")
    for k, name in enumerate(out_textures):
        params.append(f"texture2d<half, access::write> out{k} [[texture({len(textures) + k})]]")
    params += DIRTY_PARAMS
    params += ["uint2 tgid [[threadgroup_position_in_grid]]", "uint tid [[thread_index_in_threadgroup]]"]
    emit(f"kernel void artcnn_pass{index}(" + ",\n    ".join(params) + ")")
    emit("{")
    emit_dirty_check(emit, BLOCK_W // CELL_W)
    emit(f"    threadgroup half4 staged[{len(textures)}][{STAGE_H}][{STAGE_W}];")
    emit(f"    const int2 block = int2(tgid) * int2({BLOCK_W}, {BLOCK_H});")
    emit(f"    for (uint i = tid; i < {len(textures) * STAGE_H * STAGE_W}; i += {THREADS}) {{")
    emit(f"        const uint t = i / {STAGE_H * STAGE_W}, r = i % {STAGE_H * STAGE_W};")
    emit(f"        const int2 px = block - 1 + int2(r % {STAGE_W}, r / {STAGE_W});")
    emit("        switch (t) {")
    for i, t in enumerate(textures):
        emit(f"        case {i}: staged[{i}][r / {STAGE_W}][r % {STAGE_W}] = load({names[t]}, px); break;")
    emit("        }")
    emit("    }")
    emit("    threadgroup_barrier(mem_flags::mem_threadgroup);")
    emit(f"    const uint x = tid % {BLOCK_W}, y = tid / {BLOCK_W};")
    outs = layer.w.shape[0]
    for o4 in range(outs // 4):
        emit(f"    float4 acc{o4} = float4({', '.join(half(v) for v in layer.b[o4 * 4:o4 * 4 + 4])});")
    for g, (name, sign) in enumerate(layer.inputs):
        src = textures.index(name)
        for ky in range(3):
            for kx in range(3):
                v = f"staged[{src}][y + {ky}][x + {kx}]"
                if sign is not None:
                    v = f"max({'-' if sign < 0 else ''}{v}, half4(0.0h))"
                emit(f"    {{ const half4 v = {v};")
                for o4 in range(outs // 4):
                    cols = ["half4(" + ", ".join(half(layer.w[o4 * 4 + o, g * 4 + j, ky, kx]) for o in range(4)) + ")"
                            for j in range(4)]
                    emit(f"      acc{o4} += float4(half4x4({', '.join(cols)}) * v);")
                emit("    }")
    emit("    const int2 p = block + int2(x, y);")
    if layer.residual:
        emit(f"    const half4 rgb = clamp(half4(acc0) + staged[{textures.index('MAIN')}][y + 1][x + 1], 0.0h, 1.0h);")
        emit("    store(out0, p, half4(rgb.rgb, 1.0h));")
    else:
        for k in range(len(out_textures)):
            emit(f"    store(out{k}, p, half4(acc{k}));")
    emit("}")
    return "\n".join(lines) + "\n"


def is_crelu_16_to_8(layer):
    """A layer reading two 4-channel textures through CReLU (16 inputs) into 8 outputs."""
    names = [n for n, _ in layer.inputs]
    signs = [sg for _, sg in layer.inputs]
    return (not layer.residual and layer.w.shape[:2] == (8, 16) and signs == [1, 1, -1, -1]
            and names[:2] == names[2:] and len(set(names)) == 2)


def winograd_kernel(index, layer):
    """16 -> 8 conv as Winograd on simdgroup_matrix with tiles in registers.

    Lane l is row r = (q & 4) + (l / 2) % 4 and column pair c = (q & 2) * 2 + (l % 2) * 2 of an
    8x8 simdgroup matrix (q = l / 4). Input k of the first matrix is relu(x_k) and of the second
    relu(-x_k) for the 8 stored channels, so the lane reads stored channels c and c+1 of tile r's
    6x4 window and forms both halves itself. The single output matrix holds the 8 outputs.
    """
    src_a, src_b = layer.inputs[0][0], layer.inputs[1][0]
    # U[k][in][out] with in = 16 CReLU inputs, out = 8 channels.
    u = np.einsum("ak,oikl,bl->oiab", F23["G"], layer.w.astype(np.float64), F43["G"])  # [8, 16, 4, 6]
    table = np.zeros((24, 16, 8), np.float64)
    for a in range(4):
        for c in range(6):
            table[a * 6 + c] = u[:, :, a, c].T
    lines = []
    emit = lines.append
    emit(f"constant half winograd_u{index}[24 * 16 * 8] = {{{', '.join(half(x) for x in table.ravel())}}};")
    emit(f"constant half winograd_b{index}[8] = {{{', '.join(half(x) for x in layer.b)}}};")
    emit("")
    emit(f"// {' + '.join(layer.passes)} (Winograd F(4, 3) x F(2, 3), tiles in registers, products on simdgroup_matrix)")
    emit(f"kernel void artcnn_pass{index}(texture2d<half> {src_a} [[texture(0)]],")
    emit(f"    texture2d<half> {src_b} [[texture(1)]],")
    emit("    texture2d<half, access::write> out0 [[texture(2)]],")
    emit("    texture2d<half, access::write> out1 [[texture(3)]],")
    for param in DIRTY_PARAMS:
        emit(f"    {param},")
    emit("    uint2 tgid [[threadgroup_position_in_grid]],")
    emit("    uint tid [[thread_index_in_threadgroup]],")
    emit("    ushort sg [[simdgroup_index_in_threadgroup]],")
    emit("    ushort lane [[thread_index_in_simdgroup]])")
    emit("{")
    emit_dirty_check(emit, WIN_W // CELL_W)
    emit(f"    threadgroup half4 staged[2][{WIN_SH}][2][{WIN_SW // 2}];  // [texture][row][column parity][column / 2]")
    emit(f"    const int2 block = int2(tgid) * int2({WIN_W}, {WIN_H});")
    emit(f"    for (uint i = tid; i < {2 * WIN_SH * WIN_SW}; i += {THREADS}) {{")
    emit(f"        const uint t = i / {WIN_SH * WIN_SW}, r = i % {WIN_SH * WIN_SW};")
    emit(f"        const int2 px = block - 1 + int2(r % {WIN_SW}, r / {WIN_SW});")
    emit(f"        staged[t][r / {WIN_SW}][(r % {WIN_SW}) & 1][(r % {WIN_SW}) >> 1] = t == 0 ? load({src_a}, px) : load({src_b}, px);")
    emit("    }")
    emit("    threadgroup_barrier(mem_flags::mem_threadgroup);")
    emit("")
    emit("    const uint q = lane / 4;")
    emit("    const uint mr = (q & 4) + (lane / 2) % 4, mc = (q & 2) * 2 + (lane % 2) * 2;")
    emit("    const uint tx = mr, ty = sg;")
    emit("    const uint tex = mc / 4;            // stored channels mc, mc+1 are in texture mc / 4")
    emit("    const bool hi = (mc & 2) != 0;      // at components .zw")
    emit("    // Window values (relu(x_mc), relu(x_mc+1), relu(-x_mc), relu(-x_mc+1)) for rows r, columns c.")
    for r in range(4):
        for c in range(6):
            emit(f"    half4 d{r}{c};")
            emit("    {")
            emit(f"        const half4 v4 = staged[tex][ty * 2 + {r}][{c & 1}][tx * 2 + {c >> 1}];")
            emit("        const half2 v = hi ? v4.zw : v4.xy;")
            emit(f"        d{r}{c} = max(half4(v, -v), half4(0.0h));")
            emit("    }")
    emit("    // Across: t = d B_x (F(4, 3)), then down: V = B_y^T t (F(2, 3)).")
    for r in range(4):
        for c in range(6):
            emit(f"    const half4 t{r}{c} = {combo(F43['BT'][c], [f'd{r}{cc}' for cc in range(6)])};")
    for a in range(4):
        for c in range(6):
            emit(f"    const half4 v{a}{c} = {combo(F23['BT'][a], [f't{r}{c}' for r in range(4)])};")
    emit("    half2 s[2][6];  // rows of A_y^T m for output channels mc, mc+1")
    emit("    for (uint c = 0; c < 6; c++) {")
    emit("        s[0][c] = half2(0.0h);")
    emit("        s[1][c] = half2(0.0h);")
    emit("    }")
    for a in range(4):
        for c in range(6):
            k = a * 6 + c
            emit("    {")
            emit(f"        constant half *uk = winograd_u{index} + {k * 128};")
            emit("        simdgroup_half8x8 a0, a1, u0, u1;")
            emit(f"        a0.thread_elements()[0] = v{a}{c}.x;")
            emit(f"        a0.thread_elements()[1] = v{a}{c}.y;")
            emit(f"        a1.thread_elements()[0] = v{a}{c}.z;")
            emit(f"        a1.thread_elements()[1] = v{a}{c}.w;")
            for kh in range(2):
                for e in range(2):
                    emit(f"        u{kh}.thread_elements()[{e}] = uk[({kh * 8} + mr) * 8 + mc + {e}];")
            emit("        simdgroup_half8x8 c0 = make_filled_simdgroup_matrix<half, 8, 8>(0.0h);")
            emit("        simdgroup_multiply_accumulate(c0, a0, u0, c0);")
            emit("        simdgroup_multiply_accumulate(c0, a1, u1, c0);")
            emit("        const half2 m = half2(c0.thread_elements()[0], c0.thread_elements()[1]);")
            for i in range(2):
                coef = F23["AT"][i][a]
                if coef == 1:
                    emit(f"        s[{i}][{c}] += m;")
                elif coef == -1:
                    emit(f"        s[{i}][{c}] -= m;")
            emit("    }")
    emit(f"    const half2 bias = half2(winograd_b{index}[mc], winograd_b{index}[mc + 1]);")
    for i in range(2):
        for j in range(4):
            emit("    {")
            emit(f"        const half2 y = {combo(F43['AT'][j], [f's[{i}][{c}]' for c in range(6)])} + bias;")
            emit("        // The neighbor lane holds the other two channels of the 4-channel texel.")
            emit("        const half2 other = simd_shuffle_xor(y, ushort(1));")
            emit("        if (!hi) {")
            emit(f"            const int2 p = block + int2(tx * 4 + {j}, ty * 2 + {i});")
            emit("            if (tex == 0) {")
            emit("                store(out0, p, half4(y, other));")
            emit("            } else {")
            emit("                store(out1, p, half4(y, other));")
            emit("            }")
            emit("        }")
            emit("    }")
    emit("}")
    return "\n".join(lines) + "\n"


def main(glsl_path, msl_path):
    layers = A.load(glsl_path)
    names = {"MAIN": "MAIN"}
    for layer in layers:
        for s in layer.saves:
            names.setdefault(s, s)
    manifest, kernels = [], []
    radius_x = radius_y = 0
    for index, layer in enumerate(layers):
        binds = []
        for name, _ in layer.inputs:
            if name not in binds:
                binds.append(name)
        if layer.residual and "MAIN" not in binds:
            binds.append("MAIN")
        saves = "OUTPUT" if layer.residual else ",".join(layer.saves)
        if is_crelu_16_to_8(layer):
            block = f"{WIN_W}x{WIN_H}"
            kernels.append(winograd_kernel(index, layer))
            radius_x, radius_y = radius_x + 4, radius_y + 2
        else:
            block = f"{BLOCK_W}x{BLOCK_H}"
            kernels.append(layer_kernel(index, layer, names))
            radius_x, radius_y = radius_x + 1, radius_y + 1
        manifest.append(f"// PASS {index} binds={','.join(binds)} save={saves} block={block} "
                        f"threads={THREADS}x1 scale=1x1 desc={layer.passes[0]}")
    with open(msl_path, "w") as f:
        f.write(PRELUDE.format(source=glsl_path.split("/")[-1]) +
                f"// REUSE radius={radius_x}x{radius_y} cell={CELL_W}x{CELL_H}\n" +
                "\n".join(manifest) + "\n\n" + "\n".join(kernels))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
