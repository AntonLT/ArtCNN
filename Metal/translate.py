#!/usr/bin/env python3
"""Translate an ArtCNN mpv/libplacebo GLSL shader into Metal Shading Language.

Usage: translate.py GLSL/ArtCNN_C4F16_DS.glsl Metal/ArtCNN_C4F16_DS.metal [--float32]

--float32 emits full-precision kernels and storage, used only to verify the translation
against the float32 ONNX model.

Each //!HOOK pass becomes one compute kernel named artcnn_pass<N>. The weights and
arithmetic are carried over unchanged; only the libplacebo glue (texture binding,
sampling helpers, workgroup builtins) is rewritten. A pass manifest is embedded at
the top of the output as `// PASS` comment lines for the host code to read.
"""

import re
import sys
from dataclasses import dataclass, field


@dataclass
class Pass:
    desc: str
    binds: list
    save: str
    block: tuple  # output pixels per threadgroup (w, h)
    threads: tuple  # threads per threadgroup (w, h)
    scale: tuple  # output size relative to LUMA (w, h)
    components: int
    body: str = ""
    globals: list = field(default_factory=list)


def parse(src):
    passes = []
    for chunk in re.split(r"(?m)^(?=//!DESC )", src)[1:]:
        headers = dict()
        binds = []
        lines = chunk.splitlines()
        i = 0
        while i < len(lines) and lines[i].startswith("//!"):
            key, _, value = lines[i][3:].partition(" ")
            if key == "BIND":
                binds.append(value.strip())
            else:
                headers[key] = value.strip()
            i += 1
        code = "\n".join(lines[i:])
        code = re.sub(r"(?s)#extension.*?#endif\n", "", code)

        compute = [int(v) for v in headers["COMPUTE"].split()]
        scale = tuple(float(headers[k].split()[1]) for k in ("WIDTH", "HEIGHT"))
        p = Pass(desc=headers["DESC"], binds=binds, save=headers.get("SAVE", "OUTPUT"),
                 block=(compute[0], compute[1]), threads=(compute[2], compute[3]),
                 scale=scale, components=int(headers["COMPONENTS"]))

        head, _, rest = code.partition("void hook() {")
        p.globals = [l for l in head.strip().splitlines() if l.strip()]
        p.body = rest.rstrip()
        assert p.body.endswith("}"), p.desc
        p.body = p.body[:-1]
        passes.append(p)
    return passes


def m4_to_msl(match):
    values = [v.strip() for v in match.group(1).split(",")]
    assert len(values) == 16, values
    # GLSL mat4 scalar constructors fill column by column, as does this half4x4 form.
    cols = ", ".join("half4(" + ", ".join(values[c * 4:c * 4 + 4]) + ")" for c in range(4))
    return "half4x4(" + cols + ")"


def translate_code(code, p):
    tw, th = p.threads
    out = []
    for line in p.globals:
        if "gl_WorkGroupSize" in line:
            line = f"const ivec2 wg_size = ivec2({tw}, {th});"
        elif line.startswith("shared "):
            m = re.match(r"shared (\w+) (\w+)\[(\d+)\]\[isize\.y\]\[isize\.x\];", line)
            assert m, line
            line = f"threadgroup {m.group(1)} {m.group(2)}[{m.group(3)}][{th + 2}][{tw + 2}];"
        out.append("    " + line)
    code = "\n".join(out) + "\n" + code

    code = re.sub(r"(\w+)_mul \* texelFetch\(\1_raw, ([^;]*?ivec2\(\d+, \d+\)), 0\)", r"load(\1, \2)", code)
    code = re.sub(r"imageStore\(out_image, ([^;]*?ivec2\(\d+, \d+\)), ", r"store(out_image, \1, ", code)
    code = re.sub(r"M4\(([^()]*)\)", m4_to_msl, code)
    code = code.replace("barrier();", "threadgroup_barrier(mem_flags::mem_threadgroup);")
    for glsl, msl in (("gl_LocalInvocationID", "lid"), ("gl_WorkGroupID", "tgid"),
                      ("gl_GlobalInvocationID", "gid"), ("ivec2", "int2"), ("uvec2", "uint2")):
        code = re.sub(r"\b" + glsl + r"\b", msl, code)

    leftover = re.findall(r"texelFetch|imageStore|_raw\b|_mul\b|\bM4\(|gl_\w+|\bshared\b", code)
    assert not leftover, (p.desc, leftover)
    return code


PRELUDE = """\
// Generated by Metal/translate.py from {source}. Do not edit by hand.
#include <metal_stdlib>
using namespace metal;

#define V4 half4
#define F half

// The sampler returns zero outside the texture, matching the zero padding of the
// ONNX model, without a per-read bounds check.
constexpr sampler zero_border(coord::pixel, address::clamp_to_zero, filter::nearest);

static inline half4 load(texture2d<half> t, int2 p)
{{
    return t.sample(zero_border, float2(p) + 0.5f);
}}

static inline void store(texture2d<half, access::write> t, int2 p, half4 v)
{{
    if (p.x < int(t.get_width()) && p.y < int(t.get_height())) {{
        t.write(v, uint2(p));
    }}
}}
"""

DEPTH_TO_SPACE = """\
kernel void artcnn_pass{index}(texture2d<half, access::read> {src} [[texture(0)]],
                              texture2d<half, access::write> out_image [[texture(1)]],
                              uint2 gid [[thread_position_in_grid]])
{{
    if (gid.x >= out_image.get_width() || gid.y >= out_image.get_height()) {{
        return;
    }}
    half4 v = {src}.read(gid / 2);
    half y = v[(gid.y & 1) * 2 + (gid.x & 1)];
    out_image.write(half4(clamp(y, 0.0h, 1.0h), 0.0h, 0.0h, 1.0h), gid);
}}
"""


def main(glsl_path, msl_path, float32=False):
    src = open(glsl_path).read()
    passes = parse(src)
    manifest = []
    kernels = []
    for index, p in enumerate(passes):
        manifest.append(f"// PASS {index} binds={','.join(p.binds)} save={p.save} "
                        f"block={p.block[0]}x{p.block[1]} threads={p.threads[0]}x{p.threads[1]} "
                        f"scale={p.scale[0]:g}x{p.scale[1]:g} desc={p.desc}")
        if "Depth-To-Space" in p.desc:
            assert len(p.binds) == 1
            kernels.append(DEPTH_TO_SPACE.format(index=index, src=p.binds[0]))
            continue
        params = [f"texture2d<half> {name} [[texture({i})]]" for i, name in enumerate(p.binds)]
        params.append(f"texture2d<half, access::write> out_image [[texture({len(p.binds)})]]")
        params += ["uint2 gid [[thread_position_in_grid]]",
                   "uint2 lid [[thread_position_in_threadgroup]]",
                   "uint2 tgid [[threadgroup_position_in_grid]]"]
        sig = f"kernel void artcnn_pass{index}(" + ",\n    ".join(params) + ")\n{\n"
        kernels.append(f"// {p.desc}\n" + sig + translate_code(p.body, p) + "}\n")

    text = PRELUDE.format(source=glsl_path.split("/")[-1]) + "\n".join(manifest) + "\n\n" + "\n".join(kernels)
    if float32:
        text = text.replace("// PASS 0 ", "// PRECISION float32\n// PASS 0 ", 1)
        text = re.sub(r"\bhalf", "float", text).replace(".0h", ".0f")
    with open(msl_path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], "--float32" in sys.argv[3:])
